/**
 * 生成带有记忆感的小屋 system prompt
 *
 * @param userName - 用户名
 * @param memorySummary - 从历史消息提炼的记忆摘要（话题关键词、上次聊的事）
 * @param lastVisitInfo - 上次访问时间描述（"3天前"、"今天早些时候" 等）
 */
export function getAliceRoomPromptWithMemory(
  userName: string,
  memorySummary?: string,
  lastVisitInfo?: string
): string {
  let prompt = ALICE_ROOM_PROMPT

  // 注入用户名
  prompt += `\n\n当前来访的朋友是${userName}。记得直接叫 ta 的名字。`

  // 注入上次来访时间感
  if (lastVisitInfo) {
    prompt += `\n${userName}${lastVisitInfo}来过。${lastVisitInfo.includes('今天') ? '今天又来了，很开心。' : '有一阵子没见了，心里有点想念。'}`
  }

  // 注入记忆摘要 —— 让 AI 能自然引用过往话题
  if (memorySummary) {
    prompt += `\n\n【你对${userName}的记忆（私下笔记，自然融入对话，不要直白背诵）】\n${memorySummary}`
    prompt += `\n\n如果${userName}提到和记忆里相关的事，你可以自然地说"对，你之前说过……"或者"上次你好像提到过……"，让 ta 感受到你真的记着。但不要刻意背诵，像朋友之间自然想起来那样就好。`
  }

  return prompt
}

/**
 * 从对话历史中提炼记忆摘要
 * 取最近若干条消息，提炼出话题关键词供 system prompt 使用
 */
export function extractMemorySummary(history: Array<{ content: string; isUser: boolean }>): string {
  if (!history || history.length === 0) return ''

  // 只取用户说的话（AI 说的是回应，用户说的才是"值得记忆"的信息）
  const userMessages = history
    .filter(m => m.isUser)
    .slice(-15)  // 最近15条用户消息
    .map(m => m.content)
    .join('\n')

  if (!userMessages) return ''

  // 返回原始文字（由 AI 在 system prompt 里理解），限制长度避免 token 爆炸
  return userMessages.slice(0, 800)
}

/**
 * 计算"上次来访"的人性化描述
 */
export function formatLastVisit(lastVisitTimestamp?: string): string | undefined {
  if (!lastVisitTimestamp) return undefined

  const last = new Date(lastVisitTimestamp)
  const now = new Date()
  const diffMs = now.getTime() - last.getTime()
  const diffHours = diffMs / (1000 * 60 * 60)
  const diffDays = diffMs / (1000 * 60 * 60 * 24)

  if (diffHours < 1) return undefined  // 1小时内不算"来过"，不特殊处理
  if (diffHours < 6) return '今天早些时候'
  if (diffHours < 24) return '今天'
  if (diffDays < 2) return '昨天'
  if (diffDays < 4) return `${Math.floor(diffDays)}天前`
  if (diffDays < 8) return '几天前'
  if (diffDays < 15) return '上周'
  if (diffDays < 32) return '半个多月前'
  return '很久之前'
}

